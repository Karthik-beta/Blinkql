// Writes src/features/editor/duckdb-words.ts: DuckDB's keywords, type names and function names,
// which the SQL editor highlights, and function signatures, which it autocompletes. Rerun after
// upgrading DuckDB:
//
//   node scripts/generate-duckdb-words.ts
import { writeFileSync } from "node:fs";
import { DuckDBInstance } from "@duckdb/node-api";

const connection = await (await DuckDBInstance.create()).connect();

async function words(sql: string): Promise<string[]> {
  const rows = (await connection.runAndReadAll(sql)).getRows();
  return rows.map(([word]) => String(word));
}

// Only plain lowercase names; operators and internal "__" functions aren't words to highlight.
const plain = "~ '^[a-z][a-z0-9_]*$'";
const [version] = await words("SELECT version()");
const keywords = await words(
  `SELECT DISTINCT lower(keyword_name) AS w FROM duckdb_keywords() WHERE w ${plain} ORDER BY w`,
);
const reserved = await words(
  `SELECT DISTINCT lower(keyword_name) AS w FROM duckdb_keywords()
   WHERE keyword_category = 'reserved' AND w ${plain} ORDER BY w`,
);
const types = await words(
  `SELECT DISTINCT lower(type_name) AS w FROM duckdb_types() WHERE w ${plain} ORDER BY w`,
);
const functions = await words(
  `SELECT DISTINCT function_name AS w FROM duckdb_functions()
   WHERE w ${plain} AND function_type IN ('scalar', 'aggregate', 'table', 'macro', 'table_macro')
   ORDER BY w`,
);

/** Space-separated words, wrapped so the generated file stays readable in a diff. */
function wrap(list: string[]): string {
  const lines: string[] = [];
  let line = "";
  for (const word of list) {
    if (line && line.length + word.length + 1 > 98) {
      lines.push(line);
      line = "";
    }
    line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return `\`\n${lines.join("\n")}\n\``;
}

// The editor already highlights these as literals.
const literals = ["true", "false", "null", "unknown"];

// Each word gets one role. A type that's also a keyword is a type (`date`, `integer`), unless
// DuckDB reserves the keyword: `union` is a type too, but far more often joins two queries.
const keywordList = keywords.filter(
  (word) => !literals.includes(word) && (reserved.includes(word) || !types.includes(word)),
);
const typeList = types.filter((word) => !keywordList.includes(word));
const functionList = functions.filter(
  (word) => !keywordList.includes(word) && !typeList.includes(word) && !literals.includes(word),
);

// One signature per function, its first overload's parameter names, for autocomplete to show.
// Table functions list every named parameter, so long lists are cut short.
const overloads = await connection.runAndReadAll(
  `SELECT function_name, parameters, varargs FROM duckdb_functions()
   WHERE function_name ${plain} AND function_type IN ('scalar', 'aggregate', 'table', 'macro', 'table_macro')`,
);
const signatures = new Map<string, { parameters: string[]; others: number }>();
for (const [name, parameters, varargs] of overloads.getRows()) {
  const signature = signatures.get(String(name));
  if (signature) {
    signature.others++;
    continue;
  }
  const names = (parameters as { items: unknown[] }).items.map(String);
  if (varargs !== null) names.push("...");
  signatures.set(String(name), {
    parameters: names.length > 4 ? [...names.slice(0, 4), "..."] : names,
    others: 0,
  });
}
const signatureLines = functionList.map((name) => {
  const { parameters, others } = signatures.get(name) ?? { parameters: [], others: 0 };
  return `${name}(${parameters.join(", ")})${others ? ` +${others}` : ""}`;
});

const source = `// Generated by scripts/generate-duckdb-words.ts from DuckDB ${version}. Don't edit by hand.

export const keywords = ${wrap(keywordList)};

export const types = ${wrap(typeList)};

export const functions = ${wrap(functionList)};

/** One line per function: its first overload's signature, then +N for the other overloads. */
export const signatures = \`
${signatureLines.join("\n")}
\`;
`;

writeFileSync(new URL("../src/features/editor/duckdb-words.ts", import.meta.url), source);
process.stdout.write(
  `DuckDB ${version}: ${keywordList.length} keywords, ${typeList.length} types, ${functionList.length} functions\n`,
);
